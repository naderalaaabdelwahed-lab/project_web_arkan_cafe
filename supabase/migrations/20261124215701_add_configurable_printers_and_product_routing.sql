-- Configurable printers and per-product printer routing.
create table public.printers (
  id bigint generated by default as identity primary key,
  printer_key text not null unique,
  name text not null,
  printer_type text not null default 'custom'
    check (printer_type in ('kitchen', 'bar', 'cashier', 'custom')),
  connection_type text not null default 'usb'
    check (connection_type in ('usb', 'network', 'system')),
  ip_address text,
  port integer check (port is null or (port between 1 and 65535)),
  paper_width_mm integer not null default 80
    check (paper_width_mm in (58, 80)),
  is_active boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.products
  add column printer_id bigint references public.printers(id) on delete set null;

create index printers_active_type_idx
  on public.printers (is_active, printer_type, id);
create index products_printer_id_idx
  on public.products (printer_id);

alter table public.printers enable row level security;

create policy "Admins manage printers"
  on public.printers for all
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "Employees view printers"
  on public.printers for select
  to authenticated
  using (public.has_permission('menu.update'));

create policy "Employees insert printers"
  on public.printers for insert
  to authenticated
  with check (public.has_permission('menu.update'));

create policy "Employees update printers"
  on public.printers for update
  to authenticated
  using (public.has_permission('menu.update'))
  with check (public.has_permission('menu.update'));

create policy "Employees delete printers"
  on public.printers for delete
  to authenticated
  using (public.has_permission('menu.update'));

grant select, insert, update, delete on public.printers to authenticated;
grant usage, select on sequence public.printers_id_seq to authenticated;

