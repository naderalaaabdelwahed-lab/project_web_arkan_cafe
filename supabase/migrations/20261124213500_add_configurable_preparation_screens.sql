-- Configurable preparation screens and category-based ticket routing.
create table if not exists public.preparation_screens (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  station_type text not null check (station_type in ('kitchen', 'bar')),
  is_active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.preparation_screen_categories (
  screen_id bigint not null references public.preparation_screens(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (screen_id, category_id)
);

alter table public.order_items
  add column if not exists preparation_category_id bigint
  references public.categories(id) on delete set null;

update public.order_items oi
set preparation_category_id = p.category_id
from public.products p
where oi.product_id = p.id
  and oi.preparation_category_id is null;

create index if not exists preparation_screens_active_order_idx
  on public.preparation_screens (is_active, display_order, id);
create index if not exists preparation_screen_categories_category_idx
  on public.preparation_screen_categories (category_id, screen_id);
create index if not exists order_items_preparation_category_status_idx
  on public.order_items (preparation_category_id, preparation_status, order_id);

alter table public.preparation_screens enable row level security;
alter table public.preparation_screen_categories enable row level security;

grant select, insert, update, delete on public.preparation_screens to authenticated;
grant select, insert, update, delete on public.preparation_screen_categories to authenticated;
grant usage, select on sequence public.preparation_screens_id_seq to authenticated;

drop policy if exists "Users view permitted preparation screens" on public.preparation_screens;
create policy "Users view permitted preparation screens"
on public.preparation_screens for select to authenticated
using (
  public.is_admin()
  or public.has_permission('menu.update')
  or (station_type = 'kitchen' and public.has_permission('kitchen.view'))
  or (station_type = 'bar' and public.has_permission('bar.view'))
);

drop policy if exists "Menu managers create preparation screens" on public.preparation_screens;
create policy "Menu managers create preparation screens"
on public.preparation_screens for insert to authenticated
with check (public.is_admin() or public.has_permission('menu.update'));

drop policy if exists "Menu managers update preparation screens" on public.preparation_screens;
create policy "Menu managers update preparation screens"
on public.preparation_screens for update to authenticated
using (public.is_admin() or public.has_permission('menu.update'))
with check (public.is_admin() or public.has_permission('menu.update'));

drop policy if exists "Menu managers delete preparation screens" on public.preparation_screens;
create policy "Menu managers delete preparation screens"
on public.preparation_screens for delete to authenticated
using (public.is_admin() or public.has_permission('menu.update'));

drop policy if exists "Users view permitted preparation screen categories" on public.preparation_screen_categories;
create policy "Users view permitted preparation screen categories"
on public.preparation_screen_categories for select to authenticated
using (
  public.is_admin()
  or public.has_permission('menu.update')
  or exists (
    select 1 from public.preparation_screens s
    where s.id = screen_id
      and (
        (s.station_type = 'kitchen' and public.has_permission('kitchen.view'))
        or (s.station_type = 'bar' and public.has_permission('bar.view'))
      )
  )
);

drop policy if exists "Menu managers assign preparation screen categories" on public.preparation_screen_categories;
create policy "Menu managers assign preparation screen categories"
on public.preparation_screen_categories for insert to authenticated
with check (public.is_admin() or public.has_permission('menu.update'));

drop policy if exists "Menu managers remove preparation screen categories" on public.preparation_screen_categories;
create policy "Menu managers remove preparation screen categories"
on public.preparation_screen_categories for delete to authenticated
using (public.is_admin() or public.has_permission('menu.update'));

drop policy if exists "Preparation screen employees view assigned order items" on public.order_items;
create policy "Preparation screen employees view assigned order items"
on public.order_items for select to authenticated
using (
  public.is_admin()
  or exists (
    select 1
    from public.preparation_screen_categories sc
    join public.preparation_screens s on s.id = sc.screen_id
    where sc.category_id = preparation_category_id
      and s.is_active
      and (
        (s.station_type = 'kitchen' and public.has_permission('kitchen.view'))
        or (s.station_type = 'bar' and public.has_permission('bar.view'))
      )
  )
);

create or replace function public.pos_snapshot_item_station()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_station text;
  v_category_id bigint;
begin
  if new.preparation_station is null or new.preparation_category_id is null then
    select coalesce(p.preparation_station, 'kitchen'), p.category_id
      into v_station, v_category_id
    from public.products p
    where p.id = new.product_id;

    if new.preparation_station is null then
      new.preparation_station := coalesce(v_station, 'kitchen');
    end if;
    if new.preparation_category_id is null then
      new.preparation_category_id := v_category_id;
    end if;
  end if;

  new.preparation_status := coalesce(new.preparation_status, 'pending');
  new.preparation_started_at := coalesce(new.preparation_started_at, now());
  return new;
end;
$$;

create or replace function public.save_preparation_screen(
  p_id bigint,
  p_name text,
  p_slug text,
  p_station_type text,
  p_category_ids bigint[],
  p_is_active boolean,
  p_display_order integer
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_screen_id bigint;
  v_category_count integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if not (public.is_admin() or public.has_permission('menu.update')) then raise exception 'Unauthorized'; end if;
  if nullif(trim(p_name), '') is null or nullif(trim(p_slug), '') is null then
    raise exception 'Screen name and URL slug are required';
  end if;
  if p_station_type not in ('kitchen', 'bar') then raise exception 'Invalid station type'; end if;

  select count(*) into v_category_count
  from public.categories c
  where c.id = any(coalesce(p_category_ids, '{}'::bigint[]))
    and c.department = p_station_type;
  if v_category_count <> cardinality(coalesce(p_category_ids, '{}'::bigint[])) then
    raise exception 'One or more categories do not belong to the selected department';
  end if;

  if p_id is null then
    insert into public.preparation_screens(name, slug, station_type, is_active, display_order)
    values (trim(p_name), lower(trim(p_slug)), p_station_type, coalesce(p_is_active, true), coalesce(p_display_order, 0))
    returning id into v_screen_id;
  else
    update public.preparation_screens
    set name = trim(p_name), slug = lower(trim(p_slug)), station_type = p_station_type,
        is_active = coalesce(p_is_active, true), display_order = coalesce(p_display_order, 0), updated_at = now()
    where id = p_id returning id into v_screen_id;
    if v_screen_id is null then raise exception 'Preparation screen not found'; end if;
  end if;

  delete from public.preparation_screen_categories where screen_id = v_screen_id;
  insert into public.preparation_screen_categories(screen_id, category_id)
  select v_screen_id, distinct_category
  from (select distinct unnest(coalesce(p_category_ids, '{}'::bigint[])) as distinct_category) selected_categories;
  return v_screen_id;
end;
$$;

revoke all on function public.save_preparation_screen(bigint, text, text, text, bigint[], boolean, integer) from public, anon;
grant execute on function public.save_preparation_screen(bigint, text, text, text, bigint[], boolean, integer) to authenticated;

create or replace function public.complete_preparation_screen_order(p_order_id bigint, p_screen_id bigint)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_station_type text;
  v_updated integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select station_type into v_station_type from public.preparation_screens
  where id = p_screen_id and is_active;
  if v_station_type is null then raise exception 'Active preparation screen not found'; end if;
  if not (public.is_admin() or public.has_permission(v_station_type || '.view')) then raise exception 'Unauthorized'; end if;

  perform 1 from public.orders o
  where o.id = p_order_id and o.status not in ('delivered', 'cancelled') for update;
  if not found then raise exception 'Active order not found'; end if;

  update public.order_items oi
  set preparation_status = 'ready', prepared_at = now()
  where oi.order_id = p_order_id and oi.preparation_status <> 'ready'
    and oi.preparation_category_id in (
      select sc.category_id from public.preparation_screen_categories sc where sc.screen_id = p_screen_id
    );
  get diagnostics v_updated = row_count;
  if v_updated = 0 then raise exception 'No unfinished items for this screen'; end if;
  return v_updated;
end;
$$;

revoke all on function public.complete_preparation_screen_order(bigint, bigint) from public, anon;
grant execute on function public.complete_preparation_screen_order(bigint, bigint) to authenticated;
